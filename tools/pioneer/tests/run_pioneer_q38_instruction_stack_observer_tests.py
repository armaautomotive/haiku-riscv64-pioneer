    subprocess.run([os.environ.get('CXX','c++'),'-std=c++17','-O1','-g','-Wall','-Wextra','-Werror',
                    '-fsanitize=address,undefined','-DPIONEER_Q38_NATIVE_PEER_TEST_BRIDGE=1',
                    str(here/'pioneer_q38_instruction_stack_observer_test.cpp'),'-o',str(binary)],check=True)
