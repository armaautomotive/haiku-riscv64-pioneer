#!/bin/sh
# Isolated Qwen3.5 preload candidate; not selected by a driver.
set -eu
[ "$#" = 2 ] || exit 2
directory=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
cross=$(CDPATH= cd -- "$1/cross-tools-riscv64/bin" && pwd)/riscv64-unknown-haiku
output=$2
case "$output" in /*) ;; *) exit 2;; esac
[ ! -e "$output" ] && [ ! -L "$output" ] || exit 1
extra=-DPIONEER_Q38_SPAN_FAST
umask 077; mkdir -m 700 "$output"
"$cross-g++" -std=c++11 -O2 -Wall -Wextra -Werror -ffreestanding -fno-exceptions -fno-rtti \
 -fno-stack-protector -fno-pic -fno-pie -ffp-contract=off -ffunction-sections -fdata-sections \
 -fno-unwind-tables -fno-asynchronous-unwind-tables -msmall-data-limit=0 -mno-relax \
 -march=rv32imf -mabi=ilp32 -fstack-usage $extra -c "$directory/blackhole_qwen35_span.cpp" -o "$output/program.o"
"$cross-as" -march=rv32imf -mabi=ilp32 -mno-relax "$directory/blackhole_qwen38_span_start.S" -o "$output/start.o"
"$cross-ld" -m elf32lriscv --no-relax --gc-sections -T "$directory/blackhole_qwen38_block.ld" \
 "$output/start.o" "$output/program.o" -Map "$output/program.map" -o "$output/program.elf"
for section in boot text; do "$cross-objcopy" -O binary -j ".$section" "$output/program.elf" "$output/$section.bin"; done
"$cross-nm" -n "$output/program.elf" > "$output/program.symbols"
"$cross-nm" -u "$output/program.elf" > "$output/program.undefined"
if [ -s "$output/program.undefined" ]; then
 printf '%s\n' 'Q35 preload image has unresolved symbols' >&2
 exit 1
fi
"$cross-objdump" -d "$output/program.elf" > "$output/program.disassembly"
python3 - "$output" <<'PY'
import hashlib
import pathlib
import struct
import sys

out = pathlib.Path(sys.argv[1])
boot = (out / 'boot.bin').read_bytes()
text = (out / 'text.bin').read_bytes()
if boot != struct.pack('<I', 0x0006c06f) or not text or len(text) > 8192 or len(text) % 4:
    raise SystemExit('unexpected Q35 preload image layout')
symbols = (out / 'program.symbols').read_text()
if '00072060 T block_fault_park' not in symbols:
    raise SystemExit('unexpected Q35 preload fault entry')
words = struct.unpack('<%dI' % (len(text) // 4), text)
lines = [
    '/* SPDX-License-Identifier: MIT */\n',
    '#ifndef PIONEER_QWEN35_SUPPORTED_SPAN_IMAGE_H\n#define PIONEER_QWEN35_SUPPORTED_SPAN_IMAGE_H\n',
    '#include <stdint.h>\n',
    '// Generated by build_qwen35_span_image.sh; SHA-256 ' + hashlib.sha256(text).hexdigest() + '\n',
    'enum { TT_QWEN35_SUPPORTED_SPAN_CODE_BYTES=%d };\n' % len(text),
    'static inline uint32_t PioneerQwen35SupportedSpanCodeWord(unsigned word) {\n',
    ' if (word>=2048) return UINT32_MAX;\n static const uint32_t code[]={\n',
]
for i in range(0, len(words), 8):
    lines.append('  ' + ','.join('0x%08x' % w for w in words[i:i+8]) + ',\n')
lines.append(' };\n return word<sizeof(code)/sizeof(code[0])?code[word]:0;\n}\n#endif\n')
(out / 'PioneerQwen35SupportedSpanImage.h').write_text(''.join(lines), encoding='ascii')
PY
shasum -a 256 "$output/boot.bin" "$output/text.bin"
printf 'OFFLINE Qwen3.5 span image only; no driver/card/inference/speed qualification: %s\n' "$output"
