#!/usr/bin/env python3
"""Build the experimental Firefox dependencies into a private prefix.

Requires sources from prepare_sources.py and wrappers from setup_cross.py.
Never installs into Haiku, /usr/local, or the distro image. NSS integrity
files must subsequently be generated by shlibsign on the RISC-V machine.
"""
import argparse
import os
from pathlib import Path
import shlex
import shutil
import subprocess


def install_file(source, destination):
    destination = Path(destination)
    if destination.exists() or destination.is_symlink():
        destination.unlink()
    shutil.copy2(source, destination)
    destination.chmod(destination.stat().st_mode | 0o200)
    return str(destination)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--build", type=Path, required=True)
    parser.add_argument("--jobs", type=int, default=4)
    parser.add_argument("components", nargs="+", choices=("host-tools", "libffi", "libevent", "nspr", "fonts", "nss"))
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    work, build = args.work.resolve(), args.build.resolve()
    prefix, host_tools = work / "prefix", work / "host-tools"
    cross = str(build / "cross-tools-riscv64/bin/riscv64-unknown-haiku")
    logs = work / "logs"
    logs.mkdir(parents=True, exist_ok=True)
    environment = dict(os.environ)
    environment["PATH"] = str(host_tools / "bin") + os.pathsep + environment.get("PATH", "")
    target_environment = dict(environment,
        CC=str(work / "wrappers/cc"), CXX=str(work / "wrappers/cxx"),
        HOST_CC="/usr/bin/clang", AR=cross + "-ar", RANLIB=cross + "-ranlib",
        AS=cross + "-as", STRIP=cross + "-strip",
        PKG_CONFIG=str(host_tools / "bin/pkg-config"),
        PKG_CONFIG_LIBDIR=str(prefix / "lib/pkgconfig"))

    def run(command, directory, name, env=None):
        print(f"{name}: {shlex.join(map(str, command))}", flush=True)
        with (logs / (name + ".log")).open("w") as log:
            log.write("+ " + shlex.join(map(str, command)) + "\n")
            log.flush()
            subprocess.run(command, cwd=directory, env=env or environment,
                           stdout=log, stderr=subprocess.STDOUT, check=True)

    def autotools(name, source, options, env, destination=prefix, install=True):
        directory = work / (name + "-build")
        directory.mkdir(exist_ok=True)
        run([work / "source" / source / "configure", "--prefix=" + str(destination), *options],
            directory, name + "-configure", env)
        run(["make", f"-j{args.jobs}"], directory, name + "-build", env)
        if install:
            run(["make", "install"], directory, name + "-install", env)
        return directory

    standard_cross = ["--host=riscv64-unknown-haiku", "--build=aarch64-apple-darwin"]
    for component in args.components:
        if component == "host-tools":
            for name, source in (("m4", "m4-1.4.19"), ("autoconf", "autoconf-2.72"),
                                 ("pkgconf", "pkgconf-2.3.0")):
                autotools(name, source, [], environment, host_tools)
            pkgconfig = host_tools / "bin/pkg-config"
            if not pkgconfig.exists():
                pkgconfig.symlink_to("pkgconf")
        elif component == "libffi":
            autotools("libffi", "libffi-3.4.8", standard_cross + ["--disable-docs", "--disable-static"],
                      target_environment)
        elif component == "libevent":
            env = dict(target_environment, CPPFLAGS="-D_BSD_SOURCE -DEV_ENABLE=0",
                       LDFLAGS="-lbsd -lnetwork")
            autotools("libevent", "libevent-2.1.13-stable", standard_cross + [
                "--disable-static", "--disable-samples", "--disable-libevent-regress",
                "--disable-openssl"], env)
        elif component == "nspr":
            source = work / "source/nspr-4.39/nspr"
            run([host_tools / "bin/autoconf"], source, "nspr-autoconf")
            # NSPR's legacy configure uses --host for build tools and --target
            # for the library, unlike a conventional Autoconf library.
            autotools("nspr", "nspr-4.39/nspr", [
                "--host=aarch64-apple-darwin", "--target=riscv64-unknown-haiku",
                "--build=aarch64-apple-darwin", "--disable-debug", "--enable-optimize",
                "--enable-cplus", "--with-pthreads", "--enable-64bit",
                "--includedir=" + str(prefix / "include/nspr")], target_environment)
        elif component == "fonts":
            autotools("freetype", "freetype-2.14.3", standard_cross + [
                "--without-zlib", "--without-bzip2", "--without-png", "--without-harfbuzz",
                "--without-brotli", "--disable-static"], target_environment)
            autotools("expat", "expat-2.7.3", standard_cross + [
                "--without-docbook", "--without-xmlwf", "--without-examples", "--without-tests",
                "--disable-static"], target_environment)
            # Confirmed by probes/va-copy-smoke.c on the Pioneer. C99 va_copy
            # cannot be auto-run by configure during a macOS cross build.
            env = dict(target_environment, ac_cv_va_copy="C99")
            directory = autotools("fontconfig", "fontconfig-2.18.2", standard_cross + [
                "--disable-docs", "--disable-nls", "--disable-libxml2", "--disable-static",
                "--with-default-fonts=/boot/system/data/fonts",
                "--with-add-fonts=/boot/home/config/data/fonts",
                "--with-cache-dir=/boot/home/develop/firefox-port-20261019/font-cache",
                "--with-arch=riscv64"], env, install=False)
            # The top-level install target also mkdirs the *target's* cache
            # directory. Install only the private prefix assets on this host.
            for subdirectory in ("src", "fontconfig", "conf.d"):
                run(["make", "install"], directory / subdirectory,
                    "fontconfig-install-" + subdirectory.replace(".", "-"), env)
            run(["make", "install-pkgconfigDATA"], directory, "fontconfig-install-pc", env)
            run(["make", "fonts.conf"], directory, "fontconfig-generate-config", env)
            (prefix / "etc/fonts").mkdir(parents=True, exist_ok=True)
            shutil.copy2(directory / "fonts.conf", prefix / "etc/fonts/fonts.conf")
        elif component == "nss":
            source = work / "source/nss-3.130/nss"
            values = {
                "OS_TARGET": "Haiku", "OS_ARCH": "Haiku", "OS_TEST": "riscv64",
                "CPU_ARCH": "riscv64", "OS_RELEASE": "1", "USE_64": "1",
                "BUILD_OPT": "1", "NSDISTMODE": "copy",
                "NSINSTALL": str(work / "nspr-build/config/nsinstall"),
                "NSPR_INCLUDE_DIR": str(prefix / "include/nspr"), "NSPR_LIB_DIR": str(prefix / "lib"),
                "CC": str(work / "wrappers/cc"), "CCC": str(work / "wrappers/cxx"),
                "HOST_CC": "/usr/bin/clang", "AR": cross + "-ar cr $@",
                "RANLIB": cross + "-ranlib", "NSS_USE_SYSTEM_SQLITE": "",
                "USE_SYSTEM_ZLIB": "", "NSS_ENABLE_WERROR": "0", "FREEBL_NO_DEPEND": "1",
                "NSS_DISABLE_GTESTS": "1",
            }
            make = ["make", f"-j{args.jobs}", *[f"{key}={value}" for key, value in values.items()]]
            # Build libraries separately: the native shlibsign program cannot
            # be executed on macOS to produce .chk files during `make all`.
            run(make + ["export"], source, "nss-export")
            run(make + ["libs"], source / "lib", "nss-libraries")
            run(make + ["libs"], source / "cmd/lib", "nss-command-library")
            run(make + ["program"], source / "cmd/shlibsign", "nss-shlibsign")
            dist = work / "source/nss-3.130/dist"
            platform = dist / "Haiku1_cc_PTH_64_OPT.OBJ"
            for library in (platform / "lib").glob("*.so"):
                shutil.copy2(library, prefix / "lib" / library.name)
            shutil.copytree(dist / "public/nss", prefix / "include/nss", dirs_exist_ok=True,
                            copy_function=install_file)
            (prefix / "bin").mkdir(exist_ok=True)
            shutil.copy2(source / "cmd/shlibsign/Haiku1_cc_PTH_64_OPT.OBJ/shlibsign", prefix / "bin/shlibsign")
            (prefix / "lib/pkgconfig/nss.pc").write_text(
                f"prefix={prefix}\nexec_prefix=${{prefix}}\nlibdir=${{prefix}}/lib\n"
                "includedir=${prefix}/include/nss\n\nName: NSS\n"
                "Description: Network Security Services, experimental Haiku RISC-V build\n"
                "Version: 3.130\nRequires: nspr >= 4.32\n"
                "Libs: -L${libdir} -lssl3 -lsmime3 -lnss3 -lnssutil3\nCflags: -I${includedir}\n")
    print(f"Private dependency prefix: {prefix}")
    print("NSS .chk files still require native shlibsign; no distro packages were installed.")


if __name__ == "__main__":
    main()
