static inline bool PioneerMatvecShape(unsigned inputs,unsigned outputs)
{
 return (inputs==1024 || inputs==2048 || inputs==3072 || inputs==5120 || inputs==6144)
  && outputs>=16 && outputs<=TT_RUNTIME_MATVEC_OUTPUTS_MAX && (outputs&15)==0;
}
static inline uint64_t PioneerMatvecWeightBytes(unsigned inputs,unsigned outputs)
{
 return PioneerMatvecShape(inputs,outputs)?uint64_t(inputs/16)*(outputs/16)*576:0;
}
static inline bool PioneerMatvecWeightRange(uint64_t capacity,uint64_t offset,unsigned inputs,unsigned outputs)
{
 uint64_t bytes=PioneerMatvecWeightBytes(inputs,outputs);
 return bytes && PioneerResidentOffset(capacity,offset) && bytes<=capacity-offset;
}
static inline uint64_t PioneerMatvecWeightElement(unsigned inputs,unsigned k,unsigned output)
{
 return (uint64_t(output/16)*(inputs/16)+k/16)*576+16+(k%16)*32+(output%16)*2;
}
