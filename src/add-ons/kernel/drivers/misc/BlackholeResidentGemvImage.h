static inline int BlackholeResidentGemvFixtureVector(unsigned k)
{
	return int((k*7+k/8)%17)-8;
}
static inline int BlackholeResidentGemvFixtureWeight(unsigned k,unsigned column)
{
	return int((k*17+column*3+(k/16)*column)%13)-6;
}
static inline uint32_t BlackholeResidentGemvGddrWord(unsigned word,unsigned inputs)
{
	if (!BlackholeResidentGemvShape(inputs) || word>=(inputs/16)*TT_RESIDENT_MATH_GDDR_WORDS) return 0;
	unsigned chunk=word/TT_RESIDENT_MATH_GDDR_WORDS;
	uint32_t address=0x70500+(word%TT_RESIDENT_MATH_GDDR_WORDS)*4;
	int low=0,high=0;
	if (address<0x70520) {
		unsigned k=chunk*16+(address-0x70500)/2;
		low=BlackholeResidentGemvFixtureVector(k);
		high=BlackholeResidentGemvFixtureVector(k+1);
	} else if (address>=0x70710 && address<0x70910) {
		unsigned element=(address-0x70710)/2,k=chunk*16+element/16,column=element%16;
		low=BlackholeResidentGemvFixtureWeight(k,column);
		high=BlackholeResidentGemvFixtureWeight(k,column+1);
	}
	return (BlackholeFixedIntegerFp32(low)>>16)|(BlackholeFixedIntegerFp32(high)&0xffff0000);
}
static inline uint32_t BlackholeResidentGemvExpected(unsigned output,unsigned inputs)
{
	if (output>=16 || !BlackholeResidentGemvShape(inputs)) return 0;
	int sum=0;
	for (unsigned k=0;k<inputs;k++)
		sum+=BlackholeResidentGemvFixtureVector(k)*BlackholeResidentGemvFixtureWeight(k,output);
	return BlackholeFixedIntegerFp32(sum);
}
